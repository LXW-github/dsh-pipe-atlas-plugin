#!/usr/bin/env node
/**
 * Build the browser module `client.js`.
 *
 * The Pipe Atlas viewer is a dependency-free Web Component distributed as ES
 * modules. The Harness client runner loads one plain-JS factory per plugin, so
 * the vendor modules are concatenated into that factory after stripping their
 * import/export syntax, and the demo traces are embedded as JSON.
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const read = (file) => readFileSync(join(root, file), 'utf8');

const PACKAGE_NAME = '@local/dsh-pipe-atlas';

const VENDOR_FILES = ['icons.js', 'component-style.js', 'model.js', 'pipe-timeline.js'];

const rawApp = read('src/app.js');
const tagHash = createHash('sha256')
  .update(VENDOR_FILES.map((file) => read(`vendor/${file}`)).join('\n'))
  .update(rawApp)
  .digest('hex')
  .slice(0, 8);
// A content-addressed tag lets a hot-reloaded Client module define a fresh
// element instead of keeping the stale class already in the registry.
const VIEWER_TAG = `pipe-atlas-${tagHash}`;

const DEMO_FILES = {
  scheduling: 'scheduling.json',
  network: 'network.json',
  earlyStart: 'demo.json',
  minimal: 'minimal.json',
};

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*['"][^'"]+['"];?[ \t]*$/gm;
const aliasDeclarations = new Set();

function vendorSource(file) {
  const raw = read(`vendor/${file}`);
  // The vendor modules are concatenated into one scope, so aliased imports
  // (`escapeHtml as esc`) must be re-declared explicitly.
  for (const match of raw.matchAll(IMPORT_RE)) {
    for (const specifier of match[1].split(',')) {
      const [imported, local] = specifier.trim().split(/\s+as\s+/);
      if (local) aliasDeclarations.add(`const ${local} = ${imported};`);
    }
  }
  const source = raw
    .replace(/^import\s[^;]*;\s*$/gm, '')
    .replace(/^export\s+/gm, '')
    .replace(/'pipe-timeline'/g, `'${VIEWER_TAG}'`);
  if (/^\s*(import|export)\s/m.test(source)) {
    throw new Error(`vendor/${file} still contains module syntax after transformation`);
  }
  return source;
}

const demos = {};
for (const [id, file] of Object.entries(DEMO_FILES)) {
  demos[id] = JSON.parse(read(`vendor/${file}`));
}

const app = rawApp.replaceAll('__PIPE_ATLAS_VIEWER_TAG__', VIEWER_TAG);
const vendorParts = VENDOR_FILES.map((file) => `// ---- vendor/${file} ----\n${vendorSource(file)}`);
// Keep aliases after the modules that define them but before the component
// that consumes them, so an element upgrade can never hit a TDZ.
const aliases = [...aliasDeclarations].join('\n');
vendorParts.splice(vendorParts.length - 1, 0, `// ---- aliased imports ----\n${aliases}`);
const vendor = vendorParts.join('\n\n');
const demoJson = JSON.stringify(demos);

// `locale/*.json` also carries Plugin Manager display metadata. Only the flat
// panel dictionary may reach ctx.locale.register().
function localeDictionary(file) {
  const { meta, ...dictionary } = JSON.parse(read(`locale/${file}.json`));
  if (!meta || typeof meta.title !== 'string') throw new Error(`locale/${file}.json is missing meta.title`);
  if (Object.values(dictionary).some((value) => typeof value !== 'string')) {
    throw new Error(`locale/${file}.json contains a non-string panel entry`);
  }
  return dictionary;
}

const localeEn = JSON.stringify(localeDictionary('en'));
const localeZh = JSON.stringify(localeDictionary('zh'));

const output = `/* Generated by scripts/build-client.mjs — edit src/app.js or vendor/ instead. */
window.__ModuleLoader__.load({
  id: '${PACKAGE_NAME}',
  factory(require) {
    const React = require('react');
    const h = React.createElement;

    const DEMO_DATA = ${demoJson};
    const LOCALE_EN = ${localeEn};
    const LOCALE_ZH = ${localeZh};

${vendor}

${app}
  },
});
`;

writeFileSync(join(root, 'client.js'), output);
const bytes = statSync(join(root, 'client.js')).size;
console.log(`client.js written: ${(bytes / 1024).toFixed(1)} KiB`);
